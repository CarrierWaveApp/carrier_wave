//! UniFFI surface for WWFF spot decoding (`cw_net::wwff`).
//!
//! The host owns the HTTP fetch (the Spotline `/spots` HTML page); this
//! scrapes the HTML table and derives frequency / timestamp so every platform
//! presents spots identically.

use cw_net::wwff::{parse_spots_html, WwffSpot};

/// A decoded WWFF Spotline spot with derived display fields.
#[derive(uniffi::Record)]
pub struct FfiWwffSpot {
    /// Row index assigned during HTML parsing (used as an opaque identifier).
    pub id: i64,
    pub activator: String,
    /// WWFF reference, e.g. "KFF-1234".
    pub reference: String,
    pub reference_info: Option<String>,
    pub spotter: String,
    /// Frequency in MHz as a string, e.g. "14.244".
    pub frequency: String,
    pub mode: String,
    /// The raw "Info" cell from the HTML table; also used to detect RBN spots.
    pub comments: Option<String>,
    /// "RBN" when the spot was generated by an automated decoder, `None` otherwise.
    pub source: Option<String>,
    /// ISO-8601 UTC timestamp built from the Spotline "HH:MM" time column.
    pub time: String,
    /// Frequency in kHz, or `None` if the frequency string is unparseable.
    pub frequency_khz: Option<f64>,
    /// Unix epoch seconds parsed from `time`, or `None` if unparseable.
    pub timestamp_epoch_seconds: Option<f64>,
}

impl From<WwffSpot> for FfiWwffSpot {
    fn from(spot: WwffSpot) -> Self {
        let frequency_khz = spot.frequency_khz();
        let timestamp_epoch_seconds = spot.parsed_timestamp().map(|dt| dt.timestamp() as f64);
        FfiWwffSpot {
            id: spot.id as i64,
            activator: spot.activator,
            reference: spot.reference,
            reference_info: spot.reference_info,
            spotter: spot.spotter,
            frequency: spot.frequency,
            mode: spot.mode,
            comments: spot.comments,
            source: spot.source,
            time: spot.time,
            frequency_khz,
            timestamp_epoch_seconds,
        }
    }
}

/// Parse a WWFF Spotline HTML payload and return decoded spots.
/// Always returns a (possibly empty) list — the HTML scraper never hard-fails.
#[uniffi::export]
pub fn decode_wwff_spots_html(html: String) -> Vec<FfiWwffSpot> {
    parse_spots_html(&html).into_iter().map(Into::into).collect()
}
