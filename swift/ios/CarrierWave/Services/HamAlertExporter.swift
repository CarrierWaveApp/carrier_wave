// HamAlert Exporter
//
// Generates HamAlert trigger configurations from the operator's needs.
// Supports two modes: copyable text export and direct API push.
// All triggers are tagged with [CW] prefix for identification.
//
// Uses the HamAlert web API (session-based auth via /login, then
// /ajax/triggers, /ajax/trigger_update, /ajax/trigger_delete).

import CarrierWaveCore
import Foundation

// MARK: - HamAlertExporter

actor HamAlertExporter {
    // MARK: Internal

    /// Generate a human-readable text export of needs as HamAlert triggers.
    func exportAsText(
        _ snapshot: NeedsSnapshot,
        customNeeds: [CustomNeedPattern]
    ) -> String {
        let dateFormatter = DateFormatter()
        dateFormatter.dateFormat = "yyyy-MM-dd"
        let dateStr = dateFormatter.string(from: Date())

        var lines: [String] = []
        lines.append("=== Carrier Wave Needs Export (\(dateStr)) ===")
        lines.append("")

        appendDXCCLines(snapshot: snapshot, to: &lines)
        appendWASLines(snapshot: snapshot, to: &lines)
        appendPOTALines(snapshot: snapshot, to: &lines)
        appendWWFFLines(snapshot: snapshot, to: &lines)
        appendCustomLines(customNeeds: customNeeds, to: &lines)

        if lines.count <= 2 {
            lines.append("No active needs to export.")
            lines.append("")
        }

        lines.append("Generated by Carrier Wave")
        return lines.joined(separator: "\n")
    }

    /// Push needs as HamAlert triggers via the web API.
    /// Takes a backup of all existing triggers before making changes.
    func pushToHamAlert(
        _ snapshot: NeedsSnapshot,
        customNeeds: [CustomNeedPattern],
        username: String,
        password: String
    ) async throws -> HamAlertExportResult {
        let session = URLSession(configuration: .ephemeral)

        try await login(
            session: session, username: username, password: password
        )

        // Backup all existing triggers before making changes
        let allTriggers = try await fetchAllTriggers(session: session)
        if !allTriggers.isEmpty {
            _ = try HamAlertBackupManager.save(allTriggers)
        }

        let triggers = buildTriggers(snapshot, customNeeds: customNeeds)
        let deleted = try await deleteExistingCWTriggers(session: session)

        var created = 0
        for trigger in triggers {
            do {
                try await createTrigger(trigger, session: session)
                created += 1
            } catch {
                continue
            }
        }

        return HamAlertExportResult(
            triggersCreated: created,
            triggersDeleted: deleted,
            totalNeeds: triggers.count
        )
    }

    /// Restore triggers from a backup, replacing ALL current triggers.
    func restoreBackup(
        _ entry: HamAlertBackupEntry,
        username: String,
        password: String
    ) async throws -> HamAlertRestoreResult {
        let session = URLSession(configuration: .ephemeral)

        try await login(
            session: session, username: username, password: password
        )

        let deleted = try await deleteAllTriggers(session: session)

        let triggers = try HamAlertBackupManager.loadTriggers(from: entry)
        var restored = 0
        for trigger in triggers {
            do {
                try await createRawTrigger(trigger, session: session)
                restored += 1
            } catch {
                continue
            }
        }

        return HamAlertRestoreResult(
            triggersRestored: restored,
            triggersDeleted: deleted,
            totalInBackup: triggers.count
        )
    }

    // MARK: Private

    // MARK: Text Export Helpers

    private func appendDXCCLines(
        snapshot: NeedsSnapshot,
        to lines: inout [String]
    ) {
        let tier = snapshot.dxcc.nextTier
        guard let tierName = tier.name else {
            return
        }
        let worked = snapshot.dxcc.entitiesWorkedCount
        let gridNote = snapshot.dxcc.gridSquare.map { " from \($0)" } ?? ""
        lines.append(
            "DXCC Progress: \(worked)/\(tier.threshold)"
                + " (\(tier.threshold - worked) to \(tierName))\(gridNote)"
        )
        lines.append("")
    }

    private func appendWASLines(
        snapshot: NeedsSnapshot,
        to lines: inout [String]
    ) {
        guard !snapshot.was.isComplete else {
            return
        }
        let missing = snapshot.was.statesMissing.sorted()
        lines.append("WAS States Needed (\(missing.count)):")
        lines.append("  \(missing.joined(separator: ", "))")
        lines.append("")
        lines.append("Suggested HamAlert Trigger:")
        lines.append(
            "  [CW-WAS] state=\(missing.joined(separator: " OR "))"
        )
        lines.append("")
    }

    private func appendPOTALines(
        snapshot: NeedsSnapshot,
        to lines: inout [String]
    ) {
        guard snapshot.potaHunter.parksRemaining > 0 else {
            return
        }
        let tierLabel = snapshot.potaHunter.nextTierName ?? "next tier"
        lines.append(
            "POTA Hunter: \(snapshot.potaHunter.parksWorked.count) parks,"
                + " \(snapshot.potaHunter.parksRemaining) to \(tierLabel)"
        )
        lines.append("  (Any new POTA park spot is a match)")
        lines.append("")
    }

    private func appendWWFFLines(
        snapshot: NeedsSnapshot,
        to lines: inout [String]
    ) {
        guard snapshot.wwffHunter.referencesRemaining > 0 else {
            return
        }
        let tierLabel = snapshot.wwffHunter.nextTierName ?? "next tier"
        lines.append(
            "WWFF Hunter: \(snapshot.wwffHunter.referencesWorked.count) refs,"
                + " \(snapshot.wwffHunter.referencesRemaining) to \(tierLabel)"
        )
        lines.append("  (Any new WWFF reference spot is a match)")
        lines.append("")
    }

    private func appendCustomLines(
        customNeeds: [CustomNeedPattern],
        to lines: inout [String]
    ) {
        guard !customNeeds.isEmpty else {
            return
        }
        lines.append("Custom Watches:")
        for need in customNeeds {
            lines.append("  \(need.pattern) (\(need.label))")
        }
        lines.append("")
        lines.append("Suggested HamAlert Triggers:")
        for need in customNeeds {
            let typeLabel = switch need.patternType {
            case .callsign: "callsign"
            case .entity: "callsign"
            case .state: "state"
            case .parkRef: "comment"
            }
            lines.append("  [CW-Custom] \(typeLabel)=\(need.pattern)")
        }
        lines.append("")
    }

    // MARK: Trigger Building

    private func buildTriggers(
        _ snapshot: NeedsSnapshot,
        customNeeds: [CustomNeedPattern]
    ) -> [HamAlertTrigger] {
        var triggers: [HamAlertTrigger] = []

        if !snapshot.was.statesMissing.isEmpty {
            triggers.append(HamAlertTrigger(
                name: "\(Self.cwTriggerPrefix) WAS Needed States",
                conditions: HamAlertConditions(
                    callsign: nil,
                    state: snapshot.was.statesMissing.sorted()
                        .joined(separator: ","),
                    mode: nil
                ),
                comment: "Carrier Wave WAS tracking",
                actions: ["app"]
            ))
        }

        for need in customNeeds {
            let conditions = switch need.patternType {
            case .callsign,
                 .entity:
                HamAlertConditions(
                    callsign: need.pattern, state: nil, mode: nil
                )
            case .state:
                HamAlertConditions(
                    callsign: nil, state: need.pattern, mode: nil
                )
            case .parkRef:
                HamAlertConditions(
                    callsign: nil, state: nil, mode: nil
                )
            }
            triggers.append(HamAlertTrigger(
                name: "\(Self.cwTriggerPrefix) \(need.label)",
                conditions: conditions,
                comment: "Carrier Wave: \(need.pattern)",
                actions: ["app"]
            ))
        }

        return triggers
    }
}
