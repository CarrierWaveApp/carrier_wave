use crate::schema::{StepKind, StepSchema};

// Swift keywords that, when used as enum case names, require backticks at
// member-reference sites (e.g. `case .\`if\`:`). Names like `assert` are
// global function names, not keywords — Swift accepts the bare member form,
// and `swiftformat` will strip backticks if we emit them. Keep this list to
// true keywords only.
const RESERVED_WORDS: &[&str] = &["if", "switch", "case", "default", "for", "while", "return", "break", "continue"];

fn is_reserved_word(name: &str) -> bool {
    RESERVED_WORDS.contains(&name)
}

/// Returns true if this step kind has any `"ifOn"`-valued capability, meaning
/// the switch arm should bind the `on` parameter (`case let .name(on):`).
fn has_if_on_capability(kind: &StepKind) -> bool {
    if let serde_json::Value::Object(map) = &kind.capabilities {
        for value in map.values() {
            if value.as_str() == Some("ifOn") {
                return true;
            }
        }
    }
    false
}

fn emit_case_header(name: &str, has_if_on_binding: bool) -> String {
    if is_reserved_word(name) {
        // Reserved words must be escaped with backticks when used as a
        // member reference (e.g. `case .\`assert\`:`).
        format!("        case .`{}`:", name)
    } else if has_if_on_binding {
        format!("        case let .{}(on):", name)
    } else {
        format!("        case .{}:", name)
    }
}

fn emit_case_body(
    capabilities: &serde_json::Value,
    capability_keys: &[String],
    sentinels: &[String],
) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    let map = match capabilities {
        serde_json::Value::Object(map) => map,
        _ => {
            lines.push("            break".to_string());
            return lines;
        }
    };

    if map.is_empty() {
        lines.push("            break".to_string());
        return lines;
    }

    // Sort key handling: iterate in declaration order from the schema's capabilityKeys,
    // then sentinels, then any remaining keys (e.g. "decode").
    let mut handled: Vec<String> = Vec::new();
    let mut emitted_bit = false;
    let mut emitted_if_on = false;
    let mut sentinel_comments: Vec<String> = Vec::new();
    let mut decode_comment: Option<String> = None;

    for key in capability_keys {
        if let Some(value) = map.get(key) {
            handled.push(key.clone());
            match value {
                serde_json::Value::Bool(true) => {
                    lines.push(format!("            bits.{} = true", key));
                    emitted_bit = true;
                }
                serde_json::Value::String(s) if s == "ifOn" => {
                    // Emit multi-line form — swiftformat will expand a
                    // single-line `if on { ... }` to this anyway.
                    lines.push("            if on {".to_string());
                    lines.push(format!("                bits.{} = true", key));
                    lines.push("            }".to_string());
                    emitted_if_on = true;
                }
                _ => {}
            }
        }
    }

    for key in sentinels {
        if map.contains_key(key) {
            handled.push(key.clone());
            sentinel_comments.push(format!("            // {} sentinel", key));
        }
    }

    // Any remaining keys — currently only "decode" on rawBytes.
    for (key, _value) in map.iter() {
        if handled.contains(key) {
            continue;
        }
        if key == "decode" {
            // Indented at 8 spaces (case-header level) to match swiftformat's
            // expected style — comments inside an empty `case` body align with
            // the `case` keyword, not the would-be body statements.
            decode_comment = Some("        // decode-via-opcode-table".to_string());
        }
    }

    let has_statement = emitted_bit || emitted_if_on;
    for comment in sentinel_comments {
        lines.push(comment);
    }
    if let Some(comment) = decode_comment {
        lines.push(comment);
    }

    // Swift requires at least one statement per `case` body — a bare comment
    // doesn't count. If we only emitted comments, append `break`.
    if !has_statement {
        lines.push("            break".to_string());
    }

    lines
}

pub fn emit(schema: &StepSchema) -> anyhow::Result<String> {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED by Tools/macro-codegen — DO NOT EDIT.\n");
    out.push_str("// Source: swift/packages/CarrierWaveData/Sources/CarrierWaveData/Resources/macro-step-schema.json\n");
    out.push('\n');
    out.push_str("import Foundation\n");
    out.push('\n');
    out.push_str("// MARK: - CapabilityBits\n");
    out.push('\n');
    out.push_str("public struct CapabilityBits: Sendable {\n");
    out.push_str("    public var transmits: Bool = false\n");
    out.push_str("    public var changesFrequency: Bool = false\n");
    out.push_str("    public var changesMode: Bool = false\n");
    out.push_str("    public var changesPower: Bool = false\n");
    out.push_str("    public var usesRawBytes: Bool = false\n");
    out.push_str("}\n");
    out.push('\n');
    out.push_str("public extension RadioMacroStep {\n");
    out.push_str("    /// Generated: returns the contribution to `CapabilityBits` for this step.\n");
    out.push_str("    func capabilityContribution() -> CapabilityBits {\n");
    out.push_str("        var bits = CapabilityBits()\n");
    out.push_str("        switch self {\n");

    for kind in &schema.step_kinds {
        let has_if_on = has_if_on_capability(kind);
        out.push_str(&emit_case_header(&kind.name, has_if_on));
        out.push('\n');
        let body = emit_case_body(
            &kind.capabilities,
            &schema.capability_keys,
            &schema.capability_sentinels,
        );
        for line in body {
            out.push_str(&line);
            out.push('\n');
        }
    }

    out.push_str("        }\n");
    out.push_str("        return bits\n");
    out.push_str("    }\n");
    out.push_str("}\n");

    Ok(out)
}
