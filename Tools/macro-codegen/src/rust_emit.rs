use crate::schema::{Param, StepKind, StepSchema};

fn rust_type(ty: &str) -> &'static str {
    match ty {
        "uint" => "u64",
        "int" => "i64",
        "bool" => "bool",
        "object" => "serde_json::Value",
        // "string" | "enum" | "templateName" | "templateExpression" | "hexString"
        _ => "String",
    }
}

/// Uppercases the first character of a camelCase identifier without altering
/// internal capitalization. The schema authors hand-write step names in
/// camelCase with intentional acronym casing (`setPTT`, `sendCW`), so we
/// preserve their choices verbatim — `heck::ToPascalCase` would helpfully
/// downcase `PTT` to `Ptt` and `CW` to `Cw`, losing meaning.
fn pascal_case(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// Returns the field declaration for a single param, e.g.
/// `durationMs: u64`, or `#[serde(rename = "protocol")] protocol_: String`,
/// or `args: Option<serde_json::Value>`.
fn emit_param_field(param: &Param) -> String {
    let base_ty = rust_type(&param.ty);
    let ty = if param.required {
        base_ty.to_string()
    } else {
        format!("Option<{}>", base_ty)
    };
    // Rust treats `protocol` as a reserved-style identifier in some contexts;
    // emit the serde rename + `_` suffix to keep the on-the-wire shape stable.
    if param.name == "protocol" {
        format!("#[serde(rename = \"protocol\")] protocol_: {}", ty)
    } else {
        format!("{}: {}", param.name, ty)
    }
}

fn emit_variant_fields(step: &StepKind) -> String {
    let parts: Vec<String> = step.params.iter().map(emit_param_field).collect();
    parts.join(", ")
}

/// Returns true if this step has any `"ifOn"`-valued capability — the match arm
/// must then bind `on` in the pattern.
fn has_if_on_capability(kind: &StepKind) -> bool {
    if let serde_json::Value::Object(map) = &kind.capabilities {
        for value in map.values() {
            if value.as_str() == Some("ifOn") {
                return true;
            }
        }
    }
    false
}

fn emit_match_arm(
    step: &StepKind,
    capability_keys: &[String],
    capability_sentinels: &[String],
) -> String {
    let variant = pascal_case(&step.name);
    let has_if_on = has_if_on_capability(step);
    let pattern = if has_if_on {
        format!("Self::{} {{ on }}", variant)
    } else {
        format!("Self::{} {{ .. }}", variant)
    };

    let map = match &step.capabilities {
        serde_json::Value::Object(map) => map,
        _ => return format!("            {} => {{}}\n", pattern),
    };

    if map.is_empty() {
        return format!("            {} => {{}}\n", pattern);
    }

    let mut body_lines: Vec<String> = Vec::new();
    let mut handled: Vec<String> = Vec::new();
    let mut sentinel_comments: Vec<String> = Vec::new();
    let mut decode_comment: Option<String> = None;

    for key in capability_keys {
        if let Some(value) = map.get(key) {
            handled.push(key.clone());
            match value {
                serde_json::Value::Bool(true) => {
                    body_lines.push(format!("                bits.{} = true;", key));
                }
                serde_json::Value::String(s) if s == "ifOn" => {
                    body_lines.push(format!("                if *on {{ bits.{} = true; }}", key));
                }
                _ => {}
            }
        }
    }

    for key in capability_sentinels {
        if map.contains_key(key) {
            handled.push(key.clone());
            sentinel_comments.push(format!("                // {} sentinel", key));
        }
    }

    for (key, _value) in map.iter() {
        if handled.contains(key) {
            continue;
        }
        if key == "decode" {
            decode_comment = Some("                // decode-via-opcode-table".to_string());
        }
    }

    for comment in sentinel_comments {
        body_lines.push(comment);
    }
    if let Some(comment) = decode_comment {
        body_lines.push(comment);
    }

    let mut out = String::new();
    out.push_str(&format!("            {} => {{\n", pattern));
    for line in body_lines {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str("            }\n");
    out
}

pub fn emit(schema: &StepSchema) -> anyhow::Result<String> {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED by Tools/macro-codegen — DO NOT EDIT.\n");
    out.push_str("// Source: swift/packages/CarrierWaveData/Sources/CarrierWaveData/Resources/macro-step-schema.json\n");
    out.push('\n');
    out.push_str("#![allow(non_snake_case)]\n");
    out.push('\n');
    out.push_str("use serde::{Deserialize, Serialize};\n");
    out.push('\n');
    out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n");
    out.push_str("#[serde(tag = \"kind\", rename_all = \"camelCase\")]\n");
    out.push_str("pub enum RadioMacroStep {\n");
    for kind in &schema.step_kinds {
        let variant = pascal_case(&kind.name);
        let fields = emit_variant_fields(kind);
        if fields.is_empty() {
            out.push_str(&format!("    {},\n", variant));
        } else {
            out.push_str(&format!("    {} {{ {} }},\n", variant, fields));
        }
    }
    out.push_str("}\n");
    out.push('\n');
    out.push_str("#[derive(Debug, Default, Clone, PartialEq, Serialize, Deserialize)]\n");
    out.push_str("#[serde(default, rename_all = \"camelCase\")]\n");
    out.push_str("pub struct CapabilityBits {\n");
    out.push_str("    pub transmits: bool,\n");
    out.push_str("    pub changesFrequency: bool,\n");
    out.push_str("    pub changesMode: bool,\n");
    out.push_str("    pub changesPower: bool,\n");
    out.push_str("    pub usesRawBytes: bool,\n");
    out.push_str("}\n");
    out.push('\n');
    out.push_str("impl RadioMacroStep {\n");
    out.push_str("    pub fn capability_contribution(&self) -> CapabilityBits {\n");
    out.push_str("        let mut bits = CapabilityBits::default();\n");
    out.push_str("        match self {\n");
    for kind in &schema.step_kinds {
        out.push_str(&emit_match_arm(
            kind,
            &schema.capability_keys,
            &schema.capability_sentinels,
        ));
    }
    out.push_str("        }\n");
    out.push_str("        bits\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    Ok(out)
}
